def test_store_and_read_snapshot(temp_data_dir):
    connectors.store_snapshot("devbox", SNAPSHOT)
    snaps = connectors.snapshots()
    assert len(snaps) == 1
    snap = snaps[0]
    assert snap["machine"] == "devbox"
    assert snap["stale"] is False
    p = snap["projects"][0]
    assert p["state"] == "waiting"  # any waiting session wins
    assert p["beads"]["in_progress_titles"] == ["UART scanner", "Cub OTA"]
    assert snap["projects"][1]["state"] == "working"
    assert snap["projects"][1]["name"] == "ProjectTracker"  # from path


def test_project_status_and_known_paths(temp_data_dir):
    connectors.store_snapshot("devbox", SNAPSHOT)
    status = connectors.project_status("/home/dan/code/PantryRaider")
    assert status["machine"] == "devbox"
    assert status["state"] == "waiting"
    assert connectors.project_status("/nowhere") is None
    assert connectors.project_status("") is None
