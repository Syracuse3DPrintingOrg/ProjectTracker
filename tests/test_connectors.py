def test_last_message_type_skips_metadata(tmp_path):
    f = tmp_path / "t.jsonl"
    f.write_text(
        '{"type": "user", "cwd": "/repo"}\n'
        '{"type": "assistant"}\n'
        '{"type": "system", "subtype": "turn_duration"}\n'
        '{"type": "file-history-snapshot"}\n'
        "not json\n"
    )
    assert connector_script.last_message_type(f) == "assistant"
    assert connector_script.last_message_type(tmp_path / "missing.jsonl") == ""


def test_find_cwd_skips_metadata_prefix(tmp_path):
    f = tmp_path / "t.jsonl"
    f.write_text(
        '{"type": "custom-title", "customTitle": "x"}\n'
        '{"type": "mode", "mode": "normal"}\n'
        '{"type": "user", "cwd": "/home/dan/code/Repo"}\n'
    )
    assert connector_script.find_cwd(f) == "/home/dan/code/Repo"

    # cwd only near the end of a long file: falls back to the tail scan.
    long = tmp_path / "long.jsonl"
    lines = ['{"type": "file-history-snapshot"}'] * 200
    lines.append('{"type": "user", "cwd": "/late"}')
    long.write_text("\n".join(lines) + "\n")
    assert connector_script.find_cwd(long) == "/late"

    empty = tmp_path / "empty.jsonl"
    empty.write_text("")
    assert connector_script.find_cwd(empty) == ""
